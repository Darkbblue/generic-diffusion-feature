from diffusers import DiffusionPipeline
from transformers import CLIPTokenizer, CLIPTextModel

class AbstractEncoder(nn.Module):
    def __init__(self):
        super().__init__()

    def encode(self, *args, **kwargs):
        raise NotImplementedError

class FrozenCLIPEmbedder(AbstractEncoder):
    """Uses the CLIP transformer encoder for text (from Hugging Face)"""
    def __init__(self, version="openai/clip-vit-large-patch14", device="cuda", max_length=77):
        super().__init__()
        self.tokenizer = CLIPTokenizer.from_pretrained(version, torch_dtype=torch.float32)
        self.transformer = CLIPTextModel.from_pretrained(version, torch_dtype=torch.float32)
        self.device = device
        self.max_length = max_length
        self.freeze()
        self.dtype = self.transformer.dtype

    def freeze(self):
        self.transformer = self.transformer.eval()
        for param in self.parameters():
            param.requires_grad = False

    def forward(self, text):
        batch_encoding = self.tokenizer(text, truncation=True, max_length=self.max_length, return_length=True,
                                        return_overflowing_tokens=False, padding="max_length", return_tensors="pt")
        tokens = batch_encoding["input_ids"].to(self.device)
        outputs = self.transformer(input_ids=tokens)

        z = outputs.last_hidden_state
        return z

    def encode(self, text):
        return self(text)

class UViTFeaturePipeline(DiffusionPipeline):
    def __init__(self, nnet, vae, text_encoder, scheduler=None):
        super().__init__()

        import ml_collections
        def d(**kwargs):
            """Helper of creating a config dict."""
            return ml_collections.ConfigDict(initial_dictionary=kwargs)
        def get_config():
            config = ml_collections.ConfigDict()
            config.nnet = d(
                name='uvit_imagenet',
                img_size=32,
                in_chans=4,
                patch_size=2,
                embed_dim=1152,
                depth=28,
                num_heads=16,
                mlp_ratio=4,
                qkv_bias=False,
                mlp_time_embed=False,
                num_classes=1001,
                conv=False
            )
            return config

        nnet_path = nnet
        nnet = get_nnet(**get_config().nnet)
        nnet.load_state_dict(torch.load(nnet_path, map_location='cpu'))
        nnet = nnet.to('cuda')
        nnet.dtype = torch.float32

        scheduler = Schedule(stable_diffusion_beta_schedule())

        text_encoder = FrozenCLIPEmbedder(version=text_encoder)

        self.register_modules(
            vae=vae, nnet=nnet, scheduler=scheduler, text_encoder=text_encoder,
        )

        self.preprocessor = transforms.Compose([
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.5, 0.5, 0.5], std=[0.5, 0.5, 0.5], inplace=True)
        ])

    def preprocess(self, image):
        results = []
        for i in image:
            results.append(self.preprocessor(i))
        results = torch.stack(results)
        return results

    def __call__(self, image, t, context):
        # @ torch.cuda.amp.autocast()
        def encode(_batch):
            return self.vae.encode(_batch)

        # @ torch.cuda.amp.autocast()
        def decode(_batch):
            return self.vae.decode(_batch)

        if not isinstance(image, torch.Tensor):
            x = self.preprocess(image)
        else:
            x = image
        x = x.to('cuda')
        with torch.no_grad():
            _z = encode(x)

        LSimple(_z, self.nnet, self.scheduler, t=t, y=torch.tensor([100] * x.shape[0], device=_z.device, dtype=torch.long))
